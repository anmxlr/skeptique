// Builds AI_USAGE.md from the "AI-use note" section of every receipt in board/done/, grouped by the
// ticket's sponsor track. Run from the repo root: `pnpm ai-usage` (ticket 34 runs it last).
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const RECEIPTS = join("board", "done");
const ISSUES = join(".scratch", "skeptic-v1", "issues");
const CORE = "Core";

/**
 * @param {string} fileName e.g. "04.md"
 * @param {string} text receipt markdown
 * @returns {{ ticket: string, title: string, aiUse: string | null }}
 */
export function parseReceipt(fileName, text) {
  const lines = text.replace(/\r\n/g, "\n").split("\n");
  const ticket = fileName.slice(0, 2);
  const heading = lines.find((line) => line.startsWith("# ")) ?? "";
  const title = heading
    .replace(/^#\s+\d+:\s*/, "")
    .replace(/\s*\(receipt\)\s*$/i, "")
    .trim();
  const start = lines.findIndex((line) => /^##\s+AI[- ]use( note)?\s*$/i.test(line));
  if (start === -1) return { ticket, title, aiUse: null };
  const end = lines.findIndex((line, i) => i > start && /^##?\s/.test(line));
  const aiUse = lines
    .slice(start + 1, end === -1 ? undefined : end)
    .join("\n")
    .trim();
  return { ticket, title, aiUse: aiUse || null };
}

/** @param {string} root @returns {Map<string, string>} ticket number -> area */
function areasByTicket(root) {
  const areas = new Map();
  const dir = join(root, ISSUES);
  if (!existsSync(dir)) return areas;
  for (const file of readdirSync(dir)) {
    const match = /^\*\*Tracks:\*\*\s*(.+)$/m.exec(readFileSync(join(dir, file), "utf8"));
    const tracks = match?.[1]?.replace(/\s*\(.*\)\s*$/, "").trim();
    areas.set(file.slice(0, 2), !tracks || tracks.toLowerCase() === "none" ? CORE : tracks);
  }
  return areas;
}

/**
 * @param {string} root repo root
 * @returns {{ markdown: string, missing: string[] }}
 */
export function compileAiUsage(root) {
  const areas = areasByTicket(root);
  const receipts = readdirSync(join(root, RECEIPTS))
    .filter((file) => /^\d{2}\.md$/.test(file))
    .sort()
    .map((file) => parseReceipt(file, readFileSync(join(root, RECEIPTS, file), "utf8")));

  /** @type {Map<string, typeof receipts>} */
  const grouped = new Map();
  for (const receipt of receipts.filter((r) => r.aiUse)) {
    const area = areas.get(receipt.ticket) ?? CORE;
    grouped.set(area, [...(grouped.get(area) ?? []), receipt]);
  }
  const order = [...grouped.keys()].sort((a, b) => (a === CORE ? -1 : b === CORE ? 1 : a.localeCompare(b)));
  const missing = receipts.filter((r) => !r.aiUse);

  const out = [
    "# AI usage",
    "",
    "Generated by `pnpm ai-usage` from the AI-use note in each ticket receipt (`board/done/`). Do not edit by hand.",
    "Areas follow each ticket's sponsor track; Core is shared infrastructure.",
  ];
  for (const area of order) {
    out.push("", `## ${area}`);
    for (const r of grouped.get(area) ?? []) out.push("", `### ${r.ticket}: ${r.title}`, "", r.aiUse ?? "");
  }
  if (missing.length) {
    out.push("", "## Receipts missing an AI-use note", "");
    for (const r of missing) out.push(`- ${r.ticket}: ${r.title}`);
  }
  return { markdown: `${out.join("\n")}\n`, missing: missing.map((r) => r.ticket) };
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const { markdown, missing } = compileAiUsage(process.cwd());
  writeFileSync("AI_USAGE.md", markdown);
  console.log("Wrote AI_USAGE.md");
  if (missing.length) console.error(`Receipts missing an AI-use note: ${missing.join(", ")}`);
}
